import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const rawData = JSON.parse(fs.readFileSync(path.join(__dirname, '../tokens/figma-raw-tokens.json'), 'utf8'));

const theme = {
  colors: {},
  spacing: {},
  borderRadius: {},
  fontSize: {},
  fontWeight: {},
  lineHeight: {},
};

const cssVarName = (name) => 'var(--' + name.replace(/\//g, '-').replace(/\s+/g, '-').toLowerCase() + ')';

for (const v of rawData.variables) {
  if (!v.resolvedValuesByMode) continue;
  
  const parts = v.name.split('/');
  const category = parts[0];
  const name = parts.slice(1).join('-');
  
  const varVal = cssVarName(v.name);
  
  if (category === 'color') {
    theme.colors[name] = varVal;
  } else if (category === 'spacing' || category === 'sizing') {
    theme.spacing[name] = varVal;
  } else if (category === 'radius') {
    theme.borderRadius[name] = varVal;
  } else if (category === 'font-size') {
    theme.fontSize[name] = varVal;
  } else if (category === 'font-weight') {
    theme.fontWeight[name] = varVal;
  } else if (category === 'line-height') {
    theme.lineHeight[name] = varVal;
  }
}

const fileContent = `// Auto-generated by scripts/generate-tailwind-theme.js
export const figmaTheme = ${JSON.stringify(theme, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, '../src/styles/tailwind-theme.js'), fileContent);
console.log('Generated src/styles/tailwind-theme.js');
